
import { useState } from 'react'
import API_URL from '../config/api'
import './DetectionDemo.css'

function DetectionDemo() {
  const [scenario, setScenario] = useState('BENIGN')
  const [result, setResult] = useState(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')

  async function analyzeSample() {
    setLoading(true)
    setError('')
    setResult(null)

    try {
      const response = await fetch(
        `${API_URL}/api/v1/monitoring/sample?scenario=${encodeURIComponent(scenario)}`
      )

      if (!response.ok) {
        throw new Error(`Analysis failed (${response.status})`)
      }

      const data = await response.json()
      setResult(data)

    } catch (err) {
      setError(err.message || 'Unable to analyze traffic.')
    } finally {
      setLoading(false)
    }
  }

  function changeScenario(value) {
    setScenario(value)
    setResult(null)
    setError('')
  }

  return (
    <div className="demo-page">

      <div className="demo-header">
        <h1>Interactive AI Detection Demo</h1>
        <p>
          Test the trained DDoS detection model using predefined
          CIC-IDS2017 traffic samples.
        </p>
      </div>

      <div className="demo-panel">

        <div className="demo-label">
          SELECT NETWORK TRAFFIC SCENARIO
        </div>

        <div className="demo-options">
          <button
            className={scenario === 'BENIGN' ? 'selected benign' : ''}
            onClick={() => changeScenario('BENIGN')}
            disabled={loading}
          >
            ✓ BENIGN Traffic
          </button>

          <button
            className={scenario === 'DDoS' ? 'selected ddos' : ''}
            onClick={() => changeScenario('DDoS')}
            disabled={loading}
          >
            ⚠ DDoS Traffic
          </button>
        </div>

        <p className="demo-description">
          The selected sample will be processed by the existing
          machine learning model. No prediction will be saved
          to the database.
        </p>

        <button
          className="demo-analyze"
          onClick={analyzeSample}
          disabled={loading}
        >
          {loading ? 'Analyzing Traffic...' : 'Run AI Detection'}
        </button>

        {error && (
          <div className="demo-error" role="alert">
            {error}
          </div>
        )}

      </div>

      {result && (
        <div className="demo-result">

          <h2>AI Analysis Result</h2>

          <div className="demo-result-grid">

            <div className="demo-result-card">
              <span>Model Classification</span>
              <strong className={
                result.prediction === 'DDoS'
                  ? 'demo-red'
                  : 'demo-green'
              }>
                {result.prediction}
              </strong>
            </div>

            <div className="demo-result-card">
              <span>DDoS Probability</span>
              <strong>
                {Number(result.ddos_probability_percent).toFixed(2)}%
              </strong>
            </div>

            <div className="demo-result-card">
              <span>Packets per Second</span>
              <strong>
                {Number(result.packets_per_second).toLocaleString()}
              </strong>
            </div>

            <div className="demo-result-card">
              <span>Input Scenario</span>
              <strong>{result.sample_type}</strong>
            </div>

          </div>

          <div className={
            result.prediction === 'DDoS'
              ? 'demo-message threat'
              : 'demo-message safe'
          }>
            {result.prediction === 'DDoS'
              ? 'Potential DDoS traffic identified by the AI model.'
              : 'The AI model classified this sample as benign traffic.'}
          </div>

          <p className="demo-disclaimer">
            Educational demonstration using predefined traffic samples.
            Results are generated by the trained model and do not
            represent live network monitoring or verified security
            incidents. The reported probability is a model estimate,
            not a calibrated operational risk score.
          </p>

        </div>
      )}

    </div>
  )
}

export default DetectionDemo
